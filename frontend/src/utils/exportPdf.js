import jsPDF from "jspdf";

/**
 * Exports the current analysis result as a formatted PDF report.
 * @param {object} result  - The result object from /analyze
 * @param {string} question - The original question asked
 */
export function exportAnalysisPdf(result, question) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageW  = doc.internal.pageSize.getWidth();
  const margin = 18;
  const contentW = pageW - margin * 2;
  let y = margin;

  const LINE_H  = 6;
  const SECTION_GAP = 8;

  // ── Helpers ────────────────────────────────────────────────────────────────
  const checkPage = (needed = LINE_H) => {
    if (y + needed > 275) {
      doc.addPage();
      y = margin;
    }
  };

  const addText = (text, size = 10, style = "normal", color = [30, 30, 30]) => {
    doc.setFontSize(size);
    doc.setFont("helvetica", style);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(String(text || ""), contentW);
    lines.forEach((line) => {
      checkPage();
      doc.text(line, margin, y);
      y += LINE_H;
    });
  };

  const addDivider = () => {
    checkPage(4);
    doc.setDrawColor(220, 220, 220);
    doc.line(margin, y, pageW - margin, y);
    y += 5;
  };

  const addSection = (title) => {
    checkPage(14);
    y += 3;
    doc.setFillColor(245, 245, 255);
    doc.roundedRect(margin - 2, y - 4, contentW + 4, 9, 2, 2, "F");
    doc.setFontSize(11);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(80, 60, 200);
    doc.text(title, margin, y + 1);
    y += 9;
  };

  const riskColors = {
    High:    [220, 50,  50],
    Medium:  [200, 130, 20],
    Low:     [30,  160, 80],
    Unknown: [120, 120, 120],
  };

  // ── Header ─────────────────────────────────────────────────────────────────
  // Purple header bar
  doc.setFillColor(99, 102, 241);
  doc.rect(0, 0, pageW, 22, "F");

  doc.setFontSize(16);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(255, 255, 255);
  doc.text("⚖  LegalMind AI — Analysis Report", margin, 14);

  y = 30;

  // Date
  addText(
    `Generated: ${new Date().toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" })}`,
    8, "normal", [120, 120, 120]
  );
  y += 2;

  // Question
  addSection("Question Asked");
  addText(question, 10, "normal");
  addDivider();

  // Answer — strip markdown symbols for clean PDF output
  addSection("AI Analysis");
  const cleanAnswer = (result.answer || "")
    .replace(/\*\*(.*?)\*\*/g, "$1")   // bold
    .replace(/\*(.*?)\*/g, "$1")        // italic
    .replace(/^#+\s/gm, "")             // headings
    .replace(/^[-•]\s/gm, "  • ");      // bullets
  addText(cleanAnswer, 10, "normal");
  addDivider();

  // Risk
  addSection("Risk Assessment");
  const riskLevel = result.risk_level || "Unknown";
  const riskColor = riskColors[riskLevel] ?? riskColors.Unknown;
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...riskColor);
  checkPage();
  doc.text(`${riskLevel.toUpperCase()} RISK`, margin, y);
  y += LINE_H + 2;

  if (result.risk_plain_english) {
    addText(result.risk_plain_english, 10, "normal");
    y += 2;
  }

  if (result.issues?.length > 0) {
    addText("Issues identified:", 10, "bold", [60, 60, 60]);
    result.issues.forEach((issue) => {
      addText(`  • ${issue}`, 9, "normal", [80, 80, 80]);
    });
  }
  addDivider();

  // Redlines & Counter-clauses
  if (result.redlines?.length > 0) {
    addSection("Negotiation & Redline Recommendations");
    result.redlines.forEach((r, idx) => {
      addText(`Recommendation #${idx + 1}:`, 10, "bold", [180, 83, 9]);
      if (r.risky_clause) {
        addText(`  Flagged: "${r.risky_clause}"`, 9, "normal", [185, 28, 28]);
      }
      if (r.recommended_replacement) {
        addText(`  Proposed Counter-Clause: "${r.recommended_replacement}"`, 9, "normal", [5, 150, 105]);
      }
      if (r.negotiation_rationale) {
        addText(`  Strategy: ${r.negotiation_rationale}`, 9, "italic", [75, 85, 99]);
      }
      y += 2;
    });
    addDivider();
  }


  // Sources
  addSection("Sources");
  if (result.sources?.length > 0) {
    result.sources.forEach((src) => addText(`  • ${src}`, 10, "normal"));
  } else {
    addText("No source documents.", 10, "normal", [120, 120, 120]);
  }

  // Footer on every page
  const totalPages = doc.internal.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    doc.setFontSize(7);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(160, 160, 160);
    doc.text(
      "This report is generated by LegalMind AI and does not constitute legal advice. Consult a qualified lawyer.",
      margin, 290
    );
    doc.text(`Page ${p} of ${totalPages}`, pageW - margin, 290, { align: "right" });
  }

  const filename = `LegalMind_Report_${new Date().toISOString().slice(0, 10)}.pdf`;
  doc.save(filename);
}
